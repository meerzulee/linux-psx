    before, after = original[mts_name], records[mts_name]
    C.require(after['sha256'] != before['sha256']
              and all(after[key] == before[key] for key in ('kind', 'mode', 'vermagic')),
              'MTS module mode/vermagic must remain identical with changed bytes')

