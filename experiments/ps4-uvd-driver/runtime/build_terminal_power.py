def inventory_digest(records):
    return hashlib.sha256(json.dumps(records, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def cache_inventory(root):
    """Read all source and generated bytes without following symlinks."""
    records = {}
    for directory, directories, files in os.walk(root, followlinks=False):
        for name in sorted(directories + files):
            path = Path(directory) / name
            info = path.lstat()
            relative = path.relative_to(root).as_posix()
            row = {'mode': info.st_mode & 0o777, 'mtime_ns': info.st_mtime_ns}
            if stat.S_ISLNK(info.st_mode):
                row.update(kind='symlink', target=os.readlink(path))
            elif stat.S_ISDIR(info.st_mode):
                row.update(kind='directory')
            elif stat.S_ISREG(info.st_mode):
                C.require(info.st_nlink == 1, 'Hardlinked cache file refused: ' + relative)
                row.update(kind='file', bytes=info.st_size, sha256=C.digest(path))
            else:
                raise ValueError('Special cache entry refused: ' + relative)
            after = path.lstat()
            C.require((info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns) ==
                      (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns),
                      'Cache entry changed during read: ' + relative)
            records[relative] = row
    return records


def verify_source_inventory(records, original):
    for name, expected in original.items():
        C.require(name in records and {key: records[name].get(key) for key in expected} == expected,
                  'Cached corresponding source differs: ' + name)


def verify_clone(base, source, original):
    copied = cache_inventory(source)
    C.require(copied == original, 'Reflink clone bytes/modes/timestamps or inventory differ')
    for name, row in original.items():
        left, right = (base / name).lstat(), (source / name).lstat()
        C.require((left.st_dev, left.st_ino) != (right.st_dev, right.st_ino),
                  'Clone shares an input inode: ' + name)
        if row['kind'] == 'file':
            C.require(left.st_nlink == right.st_nlink == 1, 'Hardlinks are forbidden: ' + name)
    return inventory_digest(copied)


def reflink_command(cache, source):
    return ['cp', '-a', '--reflink=always', '--', str(cache), str(source)]


def make_command():
    # Match the cached .cmd compiler spelling; absolute CC triggers a full rebuild.
    return ['make', 'ARCH=x86_64', 'LOCALVERSION=', 'CC=gcc', 'HOSTCC=gcc']


def changed_config(raw):
    old = ('CONFIG_LOCALVERSION="' + BASE.removeprefix('7.2.11') + '"').encode()
    new = ('CONFIG_LOCALVERSION="' + RELEASE.removeprefix('7.2.11') + '"').encode()
    C.require(raw.count(old) == 1 and b'CONFIG_EXTRA_FIRMWARE=""\n' in raw
              and b'CONFIG_INITRAMFS_SOURCE=""\n' in raw, 'Unexpected release or embedded firmware/initramfs')
    return raw.replace(old, new, 1)


def terminal_policy(previous):
    C.require(previous['healthy_runtime_required'] is True
              and previous['initialized_open_jobs_required'] is True
              and previous['first_close_required'] is True,
              'Unexpected inherited dev5 restart policy')
    return dict(previous, healthy_runtime_required=False, initialized_open_jobs_required=False,
                first_close_required=False, initialized_jobs_required=True,
                post_start_failure_permitted=True, startup_hw_init_completed_required=True)


def filesystem_type(path):
    result = subprocess.run(['stat', '-f', '-c', '%T', '--', str(path)],
                            capture_output=True, text=True, timeout=10, check=True)
    return result.stdout.strip()


def validate_inputs(args):
    C.require(platform.system() == 'Linux' and platform.machine() == 'x86_64', 'Native Linux x86-64 required')
    C.require(type(args.jobs) is int and args.jobs == 16 and (os.cpu_count() or 1) >= 16,
              'This incremental build requires all 16 logical CPUs')
    base, cache = args.base_package.absolute(), args.base_cache.absolute()
    for path in (base, cache):
        C.require(path.resolve(strict=True) == path and path.is_dir(), 'Canonical preserved input required')
    C.require(cache == base / ('linux-' + BASE), 'Expected the exact complete dev5 package cache')
    for name, expected in PINS.items(): checked_file(base / name, expected)
    for name, expected in CACHE_PINS.items(): checked_file(cache / name, expected)
    for name, expected in CHECKER_PINS.items(): checked_file(HERE / name, expected)
    C.require(C.digest('/usr/bin/gcc') == COMPILER_SHA, 'Pinned native compiler differs')
    patch = checked_file(args.terminal_patch, TERMINAL_PATCH_SHA)
    patch_paths(patch.read_bytes(), DELTA)
    changed_config((base / 'config').read_bytes())
    output = args.output.absolute()
    C.require(output.parent.resolve(strict=True) == output.parent and not output.exists()
              and not output.is_symlink() and output.is_relative_to(Path('/var/tmp')),
              'New canonical /var/tmp output required')
    C.require(all(not output.is_relative_to(path) and not path.is_relative_to(output) for path in (base, cache)),
              'Output overlaps preserved input')
    C.require(filesystem_type(cache) == filesystem_type(output.parent) == 'btrfs'
              and cache.stat().st_dev == output.parent.stat().st_dev,
              'Independent reflink requires the same Btrfs filesystem')
    C.require(shutil.disk_usage(output.parent).free >= MINIMUM_FREE_BYTES,
              'Need at least 4 GiB free for incremental output and complete packages')
    original = json.loads((base / 'SOURCE-ARCHIVE.json').read_text())
    records = cache_inventory(cache)
    C.require(inventory_digest(records) == CACHE_INVENTORY_SHA, 'Frozen complete dev5 build cache differs')
    verify_source_inventory(records, original)
    return base, cache, output, patch, original, records


def update_code_inventory(source, original):
    expected = dict(original)
    for name in DELTA:
        row = C.file_record(source / name)
        C.require(original[name]['kind'] == 'file' and row['mode'] == original[name]['mode']
                  and row['sha256'] != original[name]['sha256'], 'Missing/invalid declared code change: ' + name)
        expected[name] = row
    N.verify_tree(source, expected)
    return expected


